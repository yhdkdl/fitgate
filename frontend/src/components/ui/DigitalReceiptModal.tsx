import React from "react";
import type { DigitalReceipt } from "../../api/payments";

interface DigitalReceiptModalProps {
  isOpen: boolean;
  receipt: DigitalReceipt | null;
  onClose: () => void;
  gymLogo?: string | null;
}

async function downloadReceiptPdf(receipt: DigitalReceipt) {
  const { jsPDF } = await import("jspdf");
  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  const primaryColor = [37, 99, 235]; // #2563EB
  const darkColor = [15, 23, 42]; // #0F172A
  const mutedColor = [100, 116, 139]; // #64748B

  // Title / Gym Name first (Item 4)
  doc.setFont("helvetica", "bold");
  doc.setFontSize(20);
  doc.setTextColor(darkColor[0], darkColor[1], darkColor[2]);
  doc.text(receipt.gym_name || "FitGate Gym", 105, 25, { align: "center" });

  doc.setFontSize(13);
  doc.setTextColor(primaryColor[0], primaryColor[1], primaryColor[2]);
  doc.text("Official Digital Receipt", 105, 33, { align: "center" });

  doc.setFont("courier", "bold");
  doc.setFontSize(10);
  doc.setTextColor(mutedColor[0], mutedColor[1], mutedColor[2]);
  doc.text(`Receipt #${receipt.receipt_number}`, 105, 40, { align: "center" });

  if (receipt.is_reversed) {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(11);
    doc.setTextColor(239, 68, 68);
    doc.text("⚠️ REVERSED - PAYMENT CANCELLED", 105, 47, { align: "center" });
  }

  // Separator
  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(0.5);
  doc.line(25, 50, 185, 50);

  let y = 58;
  const addRow = (label: string, value: string) => {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(10);
    doc.setTextColor(mutedColor[0], mutedColor[1], mutedColor[2]);
    doc.text(label, 25, y);

    doc.setFont("helvetica", "bold");
    doc.setTextColor(darkColor[0], darkColor[1], darkColor[2]);
    doc.text(value, 185, y, { align: "right" });
    y += 8;
  };

  addRow("Member Name:", receipt.member_name || "—");
  if (receipt.member_phone) {
    addRow("Member Phone:", receipt.member_phone);
  }
  addRow("Subscription Plan:", receipt.plan_name || "—");
  if (receipt.plan_duration) {
    addRow("Plan Duration:", receipt.plan_duration);
  }
  addRow("Payment Method:", (receipt.payment_method || "").toUpperCase());
  if (receipt.bank_reference) {
    addRow("Bank Reference:", receipt.bank_reference);
  }
  if (receipt.transfer_channel) {
    addRow("Transfer Channel:", receipt.transfer_channel);
  }
  addRow("Issued By:", receipt.issued_by_name || "Staff");
  addRow("Issued At:", new Date(receipt.issued_at).toLocaleString());

  doc.line(25, y, 185, y);
  y += 10;

  // Amount
  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.setTextColor(darkColor[0], darkColor[1], darkColor[2]);
  doc.text("Total Paid:", 25, y);

  doc.setFontSize(14);
  doc.setTextColor(
    receipt.is_reversed ? 100 : 34,
    receipt.is_reversed ? 116 : 197,
    receipt.is_reversed ? 139 : 94
  );
  doc.text(`${receipt.amount_etb} ${receipt.currency || "ETB"}`, 185, y, {
    align: "right",
  });

  if (receipt.notes) {
    y += 12;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(mutedColor[0], mutedColor[1], mutedColor[2]);
    doc.text(`Notes: ${receipt.notes}`, 25, y);
  }

  // Footer
  doc.setFont("helvetica", "italic");
  doc.setFontSize(8);
  doc.setTextColor(150, 150, 150);
  doc.text("Generated by FitGate Gym Management Platform", 105, 275, {
    align: "center",
  });

  doc.save(`${receipt.receipt_number}.pdf`);
}

export const DigitalReceiptModal: React.FC<DigitalReceiptModalProps> = ({
  isOpen,
  receipt,
  onClose,
  gymLogo,
}) => {
  const [downloadingPdf, setDownloadingPdf] = React.useState(false);

  if (!isOpen || !receipt) return null;

  const handlePrint = () => {
    window.print();
  };

  const handleDownloadPdf = async () => {
    if (!receipt) return;
    try {
      setDownloadingPdf(true);
      await downloadReceiptPdf(receipt);
    } catch (err) {
      console.error("Failed to generate receipt PDF:", err);
    } finally {
      setDownloadingPdf(false);
    }
  };

  return (
    <div
      className="fixed inset-0 bg-black/75 flex items-center justify-center z-50 p-4 overflow-y-auto"
      role="dialog"
      aria-modal="true"
    >
      <div className="bg-surface border border-border rounded-xl w-full max-w-md p-6 text-text space-y-4 my-8">
        {/* Printable receipt container */}
        <div id="printable-receipt" className="space-y-4">
          {/* Gym Name & Header (Item 4: Gym name first) */}
          <div className="text-center space-y-1 border-b border-border pb-3">
            {gymLogo && (
              <img
                src={gymLogo}
                alt="Gym Logo"
                className="w-12 h-12 rounded-lg mx-auto object-cover border border-border mb-2"
              />
            )}
            <h2 className="text-xl font-black text-text tracking-tight">
              {receipt.gym_name || "FitGate Gym"}
            </h2>
            <p className="text-xs font-semibold text-primary uppercase tracking-wider">
              Official Digital Receipt
            </p>
            <p className="text-xs text-text-muted font-mono">
              Receipt #{receipt.receipt_number}
            </p>
          </div>

          {receipt.is_reversed && (
            <div className="bg-danger/10 border border-danger/30 text-danger text-xs font-bold py-2 px-3 rounded text-center">
              ⚠️ REVERSED - PAYMENT CANCELLED
            </div>
          )}

          {/* Details breakdown */}
          <div className="bg-surface-2 p-3.5 rounded-lg border border-border/80 text-xs space-y-2">
            <div className="flex justify-between">
              <span className="text-text-muted">Member:</span>
              <span className="font-semibold text-text">
                {receipt.member_name}
              </span>
            </div>
            {receipt.member_phone && (
              <div className="flex justify-between">
                <span className="text-text-muted">Phone:</span>
                <span className="font-mono text-text">
                  {receipt.member_phone}
                </span>
              </div>
            )}
            <div className="flex justify-between">
              <span className="text-text-muted">Plan:</span>
              <span className="text-text">{receipt.plan_name}</span>
            </div>
            {receipt.plan_duration && (
              <div className="flex justify-between">
                <span className="text-text-muted">Duration:</span>
                <span className="text-text">{receipt.plan_duration}</span>
              </div>
            )}
            <div className="flex justify-between">
              <span className="text-text-muted">Method:</span>
              <span className="uppercase font-semibold text-text">
                {receipt.payment_method === "bank_transfer"
                  ? "Bank Transfer"
                  : receipt.payment_method}
              </span>
            </div>
            {receipt.bank_reference && (
              <div className="flex justify-between">
                <span className="text-text-muted">Bank Ref:</span>
                <span className="font-mono text-primary font-semibold">
                  {receipt.bank_reference}
                </span>
              </div>
            )}
            {receipt.transfer_channel && (
              <div className="flex justify-between">
                <span className="text-text-muted">Channel:</span>
                <span className="text-text">{receipt.transfer_channel}</span>
              </div>
            )}
            <div className="flex justify-between">
              <span className="text-text-muted">Issued By:</span>
              <span className="text-text">{receipt.issued_by_name}</span>
            </div>
            <div className="flex justify-between">
              <span className="text-text-muted">Date:</span>
              <span className="text-text">
                {new Date(receipt.issued_at).toLocaleString()}
              </span>
            </div>
            <div className="border-t border-border pt-2 flex justify-between items-baseline">
              <span className="font-bold text-text">Total Paid:</span>
              <span
                className={`text-base font-black ${
                  receipt.is_reversed
                    ? "line-through text-text-muted"
                    : "text-success"
                }`}
              >
                {receipt.amount_etb} {receipt.currency || "ETB"}
              </span>
            </div>
            {receipt.notes && (
              <div className="border-t border-border/50 pt-1.5 text-[11px] text-text-muted">
                Notes: {receipt.notes}
              </div>
            )}
          </div>
        </div>

        {/* Action Buttons (Item 5: Download PDF + Print) */}
        <div className="flex items-center gap-2 pt-2 no-print">
          <button
            type="button"
            onClick={handleDownloadPdf}
            disabled={downloadingPdf}
            className="flex-1 bg-primary hover:bg-primary-hover text-white text-xs font-semibold py-2.5 px-3 rounded-button min-h-[44px] transition-colors flex items-center justify-center gap-1.5 disabled:opacity-50"
          >
            {downloadingPdf ? "Generating..." : "📥 Download PDF"}
          </button>
          <button
            type="button"
            onClick={handlePrint}
            className="flex-1 bg-surface-2 hover:bg-border text-text border border-border text-xs font-semibold py-2.5 px-3 rounded-button min-h-[44px] transition-colors flex items-center justify-center gap-1.5"
          >
            🖨️ Print
          </button>
          <button
            type="button"
            onClick={onClose}
            className="bg-surface-2 hover:bg-border text-text-muted hover:text-text border border-border text-xs font-semibold py-2.5 px-3 rounded-button min-h-[44px] transition-colors"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
};
